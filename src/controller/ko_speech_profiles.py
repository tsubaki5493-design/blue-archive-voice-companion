def _lookup_special_profile(char_id: str) -> dict[str, Any]:
    cid = (char_id or "").strip()
    if not cid:
        return {}
    if cid in SPECIAL_KO_SPEECH_PROFILES:
        return SPECIAL_KO_SPEECH_PROFILES[cid]
    low = cid.lower()
    for k, v in SPECIAL_KO_SPEECH_PROFILES.items():
        if k.lower() == low:
            return v
    return {}


def extract_ko_speech_profile(char_data: dict[str, Any] | None) -> dict[str, Any]:
    """Extract a rich, character-specific Korean speech profile for ANY character.

    Priority merge (field-by-field so partial overrides still inherit rich defaults):
      1. JSON `persona.speech_mechanics_kr` (or top-level `speech_mechanics_kr`)
      2. `SPECIAL_KO_SPEECH_PROFILES[id]`
      3. Dynamic derivation from `speech_mechanics_jp` + `voice_acting_profile.archetype`
    """
    if not isinstance(char_data, dict) or not char_data:
        return {
            "id": "",
            "name_kr": "캐릭터",
            "polarity": "mixed",
            "first_person_kr": "저 / 나",
            "sensei_address_kr": "선생님",
            "peer_address_kr": "",
            "register_kr": "자연스럽고 생동감 있는 한국어 구어체(반말/존댓말 일관 유지).",
            "signature_endings_kr": ["~예요", "~네요", "~야", "~네"],
            "interjections_kr": ["후훗", "저기"],
            "forbidden_kr": ["딱딱한 AI 번역투·문어체 금지"],
            "sample_lines_kr": [],
            "source": "fallback",
        }

    cid = str(char_data.get("id") or "").strip()
    name_kr = _strip_parens(str(char_data.get("name_kr") or cid or "캐릭터"))
    persona = _as_dict(char_data.get("persona"))
    sm_jp = _as_dict(char_data.get("speech_mechanics_jp")) or _as_dict(persona.get("speech_mechanics_jp"))
    vap = _as_dict(persona.get("voice_acting_profile")) or _as_dict(char_data.get("voice_acting_profile"))
    archetype = str(vap.get("archetype") or "").strip()
    polarity = _detect_ko_polarity(char_data)

    json_kr = _as_dict(persona.get("speech_mechanics_kr")) or _as_dict(char_data.get("speech_mechanics_kr"))
    special_kr = _lookup_special_profile(cid)

    fp_jp = str(sm_jp.get("first_person") or "")
    sa_jp = str(sm_jp.get("sensei_address") or "")
    peer_jp = str(sm_jp.get("peer_address_examples") or "")
    endings_jp = _as_list(sm_jp.get("signature_endings"))
    interj_jp = _as_list(sm_jp.get("interjections_and_laughs"))
    forb_jp = _as_list(sm_jp.get("forbidden_expressions"))
    user_title = str(char_data.get("user_title") or "선생님").strip()

    dyn_fp = _derive_first_person_kr(fp_jp, char_data, polarity)
    dyn_sa = _derive_sensei_address_kr(sa_jp, user_title)
    dyn_peer = _derive_peer_address_kr(peer_jp)
    dyn_reg = _derive_register_kr(sm_jp, archetype, polarity, char_data)
    dyn_endings = _derive_endings_kr(endings_jp, polarity, archetype)
    dyn_interj = _derive_interjections_kr(interj_jp, archetype)
    dyn_forb = _derive_forbidden_kr(forb_jp, polarity, dyn_fp, dyn_sa, archetype)

    def _pick_str(key: str, default: str) -> str:
        for src in (json_kr, special_kr):
            v = str(src.get(key) or "").strip()
            if v:
                return v
        return default

    def _pick_list(key: str, default: list[str]) -> list[str]:
        for src in (json_kr, special_kr):
            vals = _as_list(src.get(key))
            if vals:
                return vals
        return default

    first_person_kr = _sanitize_ko_guide_text(_pick_str("first_person_kr", dyn_fp), 80) or ("나" if polarity == "banmal" else "저")
    sensei_address_kr = _sanitize_ko_guide_text(_pick_str("sensei_address_kr", dyn_sa), 80) or "선생님"
    peer_address_kr = _sanitize_ko_guide_text(_pick_str("peer_address_kr", dyn_peer), 110)
    if peer_address_kr and len(_RE_HANGUL_PRESENT.findall(peer_address_kr)) < 2:
        peer_address_kr = ""
    register_kr = _sanitize_ko_guide_text(_pick_str("register_kr", dyn_reg), 220) or dyn_reg
    signature_endings_kr = [
        x for x in (_sanitize_ko_guide_text(v, 50) for v in _pick_list("signature_endings_kr", dyn_endings)) if x
    ]
    interjections_kr = [
        x for x in (_sanitize_ko_guide_text(v, 50) for v in _pick_list("interjections_kr", dyn_interj)) if x
    ]
    forbidden_kr = [
        x for x in (_sanitize_ko_guide_text(v, 90) for v in _pick_list("forbidden_kr", dyn_forb)) if x
    ]
    dyn_samples = _derive_sample_lines_kr(
        char_data,
        first_person_kr,
        sensei_address_kr,
        signature_endings_kr,
        interjections_kr,
        polarity,
        archetype,
    )
    sample_lines_kr = [
        x for x in (_sanitize_ko_guide_text(v, 160) for v in _pick_list("sample_lines_kr", dyn_samples)) if x
    ]

    if polarity == "banmal":
        first_person_kr = _sanitize_for_banmal(first_person_kr)
        sensei_address_kr = _sanitize_for_banmal(sensei_address_kr)
        peer_address_kr = _sanitize_for_banmal(peer_address_kr)
        register_kr = _sanitize_for_banmal(register_kr)
        signature_endings_kr = [_sanitize_for_banmal(x) for x in signature_endings_kr]
        interjections_kr = [_sanitize_for_banmal(x) for x in interjections_kr]
        forbidden_kr = [_sanitize_for_banmal(x) for x in forbidden_kr]
        sample_lines_kr = [_sanitize_for_banmal(x) for x in sample_lines_kr]

    source = "json" if json_kr else ("special" if special_kr else "derived")
    return {
        "id": cid,
        "name_kr": name_kr,
        "polarity": polarity,
        "first_person_kr": first_person_kr,
        "sensei_address_kr": sensei_address_kr,
        "peer_address_kr": peer_address_kr,
        "register_kr": register_kr,
        "signature_endings_kr": signature_endings_kr,
        "interjections_kr": interjections_kr,
        "forbidden_kr": forbidden_kr,
        "sample_lines_kr": sample_lines_kr,
        "archetype": archetype,
        "source": source,
    }


def build_korean_voice_acting_guide(
    char_data: dict[str, Any] | None,
    *,
    persona_variant: str = "official",
    include_samples: bool = True,
) -> str:
    """Build a rich Korean voice-acting prompt block for direct Korean voice mode & RVC Live."""
    vc = str(persona_variant or "official").strip().lower()
    if vc not in (
        "official",
        "fanon_mainstream",
        "fanon_pure_love",
        "fanon_spicy_meme",
        "fanon_optimal_blend",
    ):
        vc = "official"

    variant_notes = {
        "official": (
            "공식 원작 100% — 블루 아카이브 한국어판 공식 대사 톤과 원작 성격을 엄격히 유지하며, "
            "과장된 패러디나 근거 없는 캐릭터 붕괴 연출을 섞지 마라."
        ),
        "fanon_mainstream": (
            "2-A 주류 종합 — 캐릭터 고유 한국어 말투 뼈대를 100% 유지하면서, "
            "친근한 2차창작 티키타카와 다정한 순간의 자연스러운 설렘이 살아나게 연기하라."
        ),
        "fanon_pure_love": (
            "2-B 고습도 순애 — 캐릭터 고유 한국어 말투 뼈대(1인칭·호칭·어미·호흡)는 절대 깨지 말고, "
            "가까운 거리감·애정·둘만의 시간·은근한 독점 뉘앙스를 캐릭터 방식대로 촉촉하게 담아라."
        ),
        "fanon_spicy_meme": (
            "2-C 매운맛 개그 — 캐릭터 고유 한국어 말투 뼈대는 절대 깨지 말고, "
            "억울한 해명·자폭·유쾌한 태클·밈 개그 리듬이 캐릭터답게 톡톡 튀게 연기하라."
        ),
        "fanon_optimal_blend": (
            "2-D 최적 배합 — 캐릭터 고유 한국어 말투 뼈대 속에서 일상↔개그↔순애의 호흡 전환이 "
            "자연스럽게 살아나도록 입체적으로 연기하라."
        ),
    }

    profile = extract_ko_speech_profile(char_data)
    if not isinstance(char_data, dict) or not char_data:
        return (
            "[한국어 직접 음성 연기 가이드]\n"
            "- 자연스럽고 생동감 있는 한국어 구어체로 실제 성우가 연기하듯 말하라.\n"
            f"- 해석 기조: {variant_notes[vc]}"
        )

    name_kr = profile["name_kr"]
    school = _clean_text(char_data.get("school"), 30)
    club = _clean_text(char_data.get("club"), 30)
    affiliation = " / ".join(x for x in (school, club) if x and x not in ("없음", "기타", "???"))
    header = f"[한국어 직접 음성 연기 가이드: {name_kr}" + (f" ({affiliation})]" if affiliation else "]")

    persona = _as_dict(char_data.get("persona"))
    summary = _sanitize_ko_guide_text(persona.get("summary"), 160)
    polarity = profile["polarity"]
    pol_label = "반말 기반" if polarity == "banmal" else ("존댓말 기반" if polarity == "jondaetmal" else "캐릭터 고유 어조")

    lines = [
        header,
        f"- 화자 정체성: {name_kr}" + (f" — {summary}" if summary else ""),
        f"- 한국어 1인칭: {profile['first_person_kr']}",
        f"- 상대(선생님) 호칭: {profile['sensei_address_kr']}",
    ]
    if profile.get("peer_address_kr"):
        lines.append(f"- 주변 인물 호칭: {profile['peer_address_kr']}")
    lines.append(f"- 한국어 말투·호흡({pol_label}): {profile['register_kr']}")
    if profile["signature_endings_kr"]:
        lines.append("- 대표 한국어 어미: " + " / ".join(profile["signature_endings_kr"][:6]))
    if profile["interjections_kr"]:
        lines.append("- 고유 감탄사·웃음·추임새: " + " / ".join(profile["interjections_kr"][:6]))
    if profile["forbidden_kr"]:
        lines.append("- [절대 금지 (한국어 OOC 방지)]: " + " | ".join(profile["forbidden_kr"][:4]))
    lines.append(f"- 해석 기조: {variant_notes[vc]}")
    lines.append(
        "- 발화 형식: 괄호 지문·특수기호(☆♪♡＊「」)·AI 해설 없이 한국어 구어체 대사만 말하라."
    )

    if include_samples and profile["sample_lines_kr"]:
        lines.append("- 한국어 발화 참고 예시 (그대로 복사하지 말고 어미·호흡·말투만 체화할 것):")
        for idx, sample in enumerate(profile["sample_lines_kr"][:3], 1):
            lines.append(f'  {idx}) "{sample}"')

    result = "\n".join(lines)
    return _sanitize_for_banmal(result) if polarity == "banmal" else result


