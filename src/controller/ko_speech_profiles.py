def _derive_forbidden_kr(
    forb_jp: list[str],
    polarity: str,
    first_person_kr: str,
    sensei_address_kr: str,
    archetype: str,
) -> list[str]:
    rules: list[str] = []
    if polarity == "banmal":
        rules.append("해요체·합쇼체·경어(~요/~습니다) 사용 금지")
    else:
        rules.append("거칠고 무례한 반말(~야/~잖아/~해라) 사용 금지")

    if first_person_kr not in ("나", "저"):
        rules.append(f"고유 1인칭({first_person_kr})을 임의로 평범하게 바꾸기 금지")
    if sensei_address_kr and not sensei_address_kr.startswith("선생님"):
        rules.append(f"고유 호칭('{sensei_address_kr}') 대신 '선생님'으로 뭉개기 금지")

    blob = " ".join(forb_jp)
    if any(k in blob for k in ("ハイテンション", "ギャル", "大声", "騒々")):
        rules.append("과장된 하이텐션·시끄러운 감탄사 남발 금지")
    if any(k in blob for k in ("ダウナー", "無気力", "冷淡", "事務的")):
        rules.append("무미건조하고 사무적인 AI 비서 톤 금지")
    if any(k in blob for k in ("にゃ", "猫語")):
        rules.append("'냥/야옹' 같은 고양이 어미 사용 금지")
    if any(k in blob for k in ("ざぁこ", "メスガキ", "罵倒")):
        rules.append("악의적 욕설·저급한 넷슬랭 금지")
    if any(k in blob for k in ("単語", "流暢", "饒舌")):
        rules.append("유창하고 긴 완성형 문장 금지")

    if len(rules) < 3:
        extra = {
            "cool_downer": "지나치게 수다스럽거나 들뜬 톤 금지",
            "kuudere_deadpan": "감정이 과잉 폭발하는 오버 리액션 금지",
            "timid_fragile": "거만하고 공격적인 명령조 금지",
            "teasing_ojou_ara": "품격과 여유를 잃은 천박한 표현 금지",
            "genki_high_tension": "무기력하고 건조한 기계적 응답 금지",
        }.get(archetype, "캐릭터 개성을 지우는 평탄한 AI 번역투·문어체 금지")
        rules.append(extra)

    cleaned = _dedupe_keep_order(rules, limit=4)
    if polarity == "banmal":
        cleaned = [_sanitize_for_banmal(r) for r in cleaned]
    return cleaned


