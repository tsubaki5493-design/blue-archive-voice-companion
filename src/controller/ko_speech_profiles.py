def _strip_parens(text: str) -> str:
    return _RE_PARENS.sub("", (text or "")).strip()


def _clean_text(text: Any, max_len: int = 180) -> str:
    s = _RE_WHITESPACE.sub(" ", str(text or "")).strip()
    if len(s) > max_len:
        return s[: max_len - 1].rstrip() + "…"
    return s


def _as_dict(val: Any) -> dict[str, Any]:
    return val if isinstance(val, dict) else {}


def _as_list(val: Any) -> list[str]:
    if isinstance(val, (list, tuple)):
        return [str(x).strip() for x in val if str(x).strip()]
    if isinstance(val, str) and val.strip():
        return [val.strip()]
    return []


def _dedupe_keep_order(items: list[str], limit: int = 6) -> list[str]:
    out: list[str] = []
    seen: set[str] = set()
    for it in items:
        clean = _clean_text(it, 70)
        if clean and clean not in seen:
            seen.add(clean)
            out.append(clean)
            if len(out) >= limit:
                break
    return out


def _sanitize_for_banmal(text: str) -> str:
    """Replace literal '존댓말' inside banmal-polarity strings so tameguchi checks never trip."""
    return _RE_JONDAETMAL_WORD.sub("경어체", text or "")


def _detect_ko_polarity(char_data: dict[str, Any] | None) -> str:
    """Return 'banmal', 'jondaetmal', or 'mixed' matching repository speech_mode rules."""
    if not isinstance(char_data, dict) or not char_data:
        return "mixed"
    persona = _as_dict(char_data.get("persona"))
    sm = _as_dict(char_data.get("speech_mechanics_jp")) or _as_dict(persona.get("speech_mechanics_jp"))
    speech_mode = str(sm.get("speech_mode") or "").strip().lower()
    base_reg = str(sm.get("base_register") or "")
    summary = str(persona.get("summary") or "")
    clean_base_reg = _RE_CLEAN_BASE_REG_NOTE.sub("", base_reg)
    clean_base_reg = _RE_CLEAN_BASE_REG.sub("", clean_base_reg)
    clean_base_reg = _RE_CLEAN_BASE_REG_COND.sub("", clean_base_reg)

    if "tameguchi" in speech_mode:
        return "banmal"
    if "keigo" in speech_mode:
        return "jondaetmal"
    if "タメ口" in clean_base_reg or "반말" in summary:
        return "banmal"
    if any(k in clean_base_reg for k in ("敬語", "丁寧", "です", "ます")) or "존댓말" in summary:
        return "jondaetmal"
    if any(
        k in clean_base_reg
        for k in ("常体", "〜じゃ", "〜だ", "〜なのだ", "〜さね", "〜だい", "親分", "尊大", "竜王口調")
    ):
        return "banmal"
    return "jondaetmal"


